#!/usr/bin/env python3
"""Generate core/qs_effects_table.inc from the Alesis "QS6,7,8,R MIDI SYSEX SPECIFICATION" (Feb 1997), EFFECT DATA FORMAT.

Usage: python3 tools/gen_effects.py path/to/Alesis-QS678R.txt > core/qs_effects_table.inc
The spec text itself is not part of this repo.

Each configuration gets a flat list of parameters. Parameters that exist only for some effect types carry a
condition: the index (in the same list) of the type parameter, and a bit mask of the type values they apply to.
"Identical to configuration 0" ranges are copied. Typos in the spec are fixed below and listed in FIXES.
"""
import re, sys

lines = open(sys.argv[1], encoding="latin-1").read().splitlines()
start = next(n for n, l in enumerate(lines) if l.strip() == "EFFECT DATA FORMAT")
lines = lines[start:]

ROW = re.compile(r"^(\d+)\.\s+(.+?)\t\s*(x|\d)\s*\t(\d+)\t(\d+)\t(\d+)\t(-?\d+)\t\s*(\d+)\*?\t\s*(\d+)\s*\t\s*(\d+):(\d+)(?:-(\d+):(\d+))?")
COND = re.compile(r"^If (\d+)\s*=\s*(.+?)\s*\(")
CONFIG = re.compile(r"^Configuration (\d) \((.+)\):")
SECTION = re.compile(r"^([A-Z][A-Z0-9 ]+):\s*$")

FIXES = []

def parse_values(text):
    text = text.strip()
    m = re.match(r"(\d+)\s*thru\s*(\d+)", text)
    if m:
        return list(range(int(m.group(1)), int(m.group(2)) + 1))
    return [int(v) for v in re.findall(r"\d+", text)]

configs = {}      # n -> list of params
titles = {}
cur = None
section = ""
cond = None       # (spec number of type param, [values])
for raw in lines:
    l = raw.strip()
    m = CONFIG.match(l)
    if m:
        cur = int(m.group(1))
        titles[cur] = m.group(2)
        configs[cur] = []
        section, cond = "", None
        continue
    if cur is None:
        continue
    m = SECTION.match(l)
    if m:
        section, cond = m.group(1).title(), None
        continue
    m = COND.match(l)
    if m:
        cond = (int(m.group(1)), parse_values(m.group(2)))
        continue
    m = ROW.match(raw.replace("’", "'"))
    if not m:
        continue
    num, name, send, func, page, pot, off, lim, bits, hb, hbit, lb, lbit = m.groups()
    name = name.strip().replace("inut", "input").replace("treshold", "threshold").replace("Send3", "Send 3")
    if "spare" in name.lower():
        continue
    hb, hbit = int(hb), int(hbit)
    if lb is None:
        lo = hb * 8 + hbit
    else:
        lo = int(lb) * 8 + int(lbit)
    send = -1 if send == "x" else int(send)
    ms = re.search(r"Send (\d)", section)
    if ms:  # the section header is right where the row's send column or name prefix has a typo (detune, config 1 pitch 3)
        n_send = int(ms.group(1))
        if send != n_send - 1 or re.match(r"Send \d ", name) and not name.startswith(f"Send {n_send} "):
            FIXES.append(f"config {cur} {section}: {name} send {send}")
        send = n_send - 1
        name = re.sub(r"^Send \d ", f"Send {n_send} ", name)
    # Block from the parameter's own name where the spec's section header is off (config 2 lists its Lezlie under PITCH).
    sec = section
    for kind in ("Lezlie", "Overdrive"):
        if kind.lower() in name.lower() and not sec.startswith(kind):
            FIXES.append(f"config {cur} {name}: section {sec} -> {kind}")
            sec = re.sub(r"^\w+", kind, sec)
    configs[cur].append(dict(num=int(num), name=name, section=sec, send=send,
                             func=int(func), page=int(page), pot=int(pot), off=int(off), lim=int(lim), bits=int(bits),
                             lo=lo, cond=cond))

# Configuration 2's "Send 1 delay input" is listed as 0-99, but factory patches hold values up to 198: it is the same
# -99..99 balance as in configuration 0.
for p in configs[2]:
    if p["name"] == "Send 1 delay input" and p["off"] == 0:
        p["off"], p["lim"] = -99, 198
        FIXES.append("config 2 Send 1 delay input: offset -99, limit 198 (factory patches use up to 198)")

# Configuration 2 and 3 reuse ranges of configuration 0.
def copy_range(dst, lo, hi):
    out = [dict(p) for p in configs[0] if lo <= p["num"] <= hi]
    configs[dst].extend(out)

copy_range(2, 26, 88)          # "Parameters 26 through 88 are identical to configuration 0."
c3_own = configs[3]
configs[3] = []
copy_range(3, 11, 56)          # pitch/delay/reverb sends 1 and 2
configs[3].extend(c3_own)      # its own send 2 reverb, EQ and modulation

# The spec's config 0 delay send 2 rows lack the "Send 2" condition values for type 47; COND handles it.
for n, ps in configs.items():
    # Resolve conditions to the index of the type parameter in this list.
    for p in ps:
        if p["cond"]:
            tnum, vals = p["cond"]
            idx = next((i for i, q in enumerate(ps) if q["num"] == tnum and q["cond"] is None), -1)
            p["condIndex"] = idx
            p["condMask"] = sum(1 << v for v in vals)
        else:
            p["condIndex"], p["condMask"] = -1, 0

def cstr(s):
    return '"' + s.replace('"', '\\"') + '"'

print("// Generated by tools/gen_effects.py from the QS SysEx specification's EFFECT DATA FORMAT. Do not edit by hand.")
print("// Fields: section, name, send (-1 = not per send), func, page, pot, offset, limit, low bit, bits, condition index, mask.")
for n in sorted(configs):
    print(f"static const EffectParam kConfig{n}[] = {{")
    for p in configs[n]:
        print(f"    {{{cstr(p['section'])}, {cstr(p['name'])}, {p['send']}, {p['func']}, {p['page']}, {p['pot']}, {p['off']}, "
              f"{p['lim']}, {p['lo']}, {p['bits']}, {p['condIndex']}, {p['condMask']}}},")
    print("};")
for f in FIXES:
    print("// fixed: " + f)
print("static const EffectConfigDef kConfigs[] = {")
for n in sorted(configs):
    print(f"    {{{cstr(titles[n])}, kConfig{n}, int(std::size(kConfig{n}))}},")
print("};")

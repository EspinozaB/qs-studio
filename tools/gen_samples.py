#!/usr/bin/env python3
"""Build core/qs_samples.inc: the sample names per group, in panel order, for each QS model.

Source: the sample charts in the Alesis QS6 and QS7/QS8 reference manuals (pdftotext -layout output).
Usage: python3 tools/gen_samples.py QS6_Manual.txt QS7_QS8.txt > core/qs_samples.inc
Known manual scan errors are fixed in FIXES below (checked against a QSR ROM directory).
"""
import re, sys

def block(path, start_pat, end_pat):
    lines = open(path, encoding="utf-8", errors="replace").read().splitlines()
    i = next(n for n, l in enumerate(lines) if re.search(start_pat, l))
    j = next(n for n in range(i + 1, len(lines)) if re.search(end_pat, lines[n]))
    return lines[i:j]

FOOTER = re.compile(r"Reference Manual|Chapter \d|Editing Programs|^\s*\d+\s*$|^\s*Group\s+Voice")

def parse(lines, labels):
    """labels: list of (regex for the label at line start, group id). Returns {group id: [names]}."""
    out, cur, li = {}, None, 0
    for l in lines:
        if not l.strip() or FOOTER.search(l):
            continue
        m = re.match(r"^\s{6,16}(" + labels[li][0] + r")\s+(\S.*)$", l) if li < len(labels) else None
        if m:
            cur = labels[li][1]
            out[cur] = m.group(2)
            li += 1
            continue
        m2 = re.match(r"^\s{6,16}(FX)\s{2,}(\S.*)$", l)  # "Percus / FX" label split over two lines
        if m2 and cur is not None:
            out[cur] += " " + m2.group(2)
            continue
        if cur is not None and re.match(r"^\s{15,}\S", l):
            out[cur] += " " + l.strip()
    res = {}
    for g, text in out.items():
        names = [re.sub(r"\s+", " ", n).strip() for n in re.split(r",", text)]
        res[g] = [n for n in names if n]
    return res

KBD = [(r"Piano", 0), (r"Chromatc|Chromatic|Chrom", 1), (r"Organ", 2), (r"Guitar", 3), (r"Bass", 4), (r"String", 5),
       (r"Brass", 6), (r"Wdwind|Woodwind", 7), (r"Synth", 8), (r"Wave", 9), (r"Noise", 10), (r"Voice", 11), (r"Ethnic", 12),
       (r"Drums", 13), (r"Percus", 14), (r"SndFX|Snd FX|Sound FX", 15), (r"Rhythm", 24)]

def kbd_labels(found):
    return [l for l in KBD]

FIXES = {  # (model, kind, group, 1-based number): name. Checked against a QSR ROM directory.
    ("QS78", "kbd", 0, 15): "NoHammer L",
    ("QS78", "kbd", 1, 21): "FMTub/NUL",
    ("QS78", "kbd", 24, 70): "Conga Loop",
    ("QS78", "kbd", 24, 88): "Tri Loop",
    ("QS78", "drum", 3, 22): "Ride Cym 1",
    ("QS78", "drum", 6, 44): "JazzPicked",
    ("QS78", "drum", 13, 66): "Agogo Loop",
    ("QS78", "drum", 13, 70): "Conga Loop",
}
INSERTS = {("QS78", "drum", 2): (22, "CanonTomM1")}  # missing from the manual chart

def emit(model, kind, table):
    for g in sorted(table):
        names = table[g]
        ins = INSERTS.get((model, kind, g))
        if ins:
            names.insert(ins[0] - 1, ins[1])
        for (m, k, gg, n), fix in FIXES.items():
            if m == model and k == kind and gg == g and n <= len(names):
                names[n - 1] = fix
        joined = ", ".join('"' + n.replace('"', '\\"') + '"' for n in names)
        print(f'    {{"{model}", {"true" if kind == "drum" else "false"}, {g}, {{{joined}}}}},')

qs6, qs78 = sys.argv[1], sys.argv[2]
qs6_kbd = parse(block(qs6, r"^\s+Piano\s{2,}GrandPiano", r"Pop Loop, Syn Loop, Tri LoopHd"), KBD)
qs6_kbd.setdefault(24, [])
# the last line of the QS6 rhythm list sits on the end marker line
qs6_kbd[24] += ["Pop Loop", "Syn Loop", "Tri LoopHd", "Tri LoopSf"]
qs78_kbd = parse(block(qs78, r"^\s+Piano\s{2,}GrndPianoL", r"^\s+LEVEL\s*$|PITCH|^\s{10}[A-Z]{4,}\s*$"), KBD)
QS6_DRUM = [(r"Kick", 0), (r"Snare", 1), (r"Hi Hat", 2), (r"Toms", 3), (r"Cymbal", 4), (r"Percus", 5), (r"Percus", 6),
            (r"Wave", 7), (r"Rhythm", 8)]
qs6_drum = parse(block(qs6, r"^\s+Kick\s{2,}Stab Kick", r"^\s+LEVEL\s*$"), QS6_DRUM)
QS78_DRUM = [(r"Kick", 0), (r"Snare", 1), (r"Toms", 2), (r"Cymbal", 3), (r"Percus", 4), (r"Snd FX|SndFX", 5), (r"Wave", 6),
             (r"Rhythm", 13)]
qs78_drum = parse(block(qs78, r"^\s+Kick\s{2,}FloppyKik1", r"^\s+LEVEL\s*$"), QS78_DRUM)

print("// Generated by tools/gen_samples.py from the sample charts in the Alesis QS6 and QS7/QS8 reference manuals.")
print("// Fields: model, drum (drum-sound groups) or keyboard, group number as stored in programs, names by sample number 1..n.")
print("// The QS6 drum group numbers follow the manual's chart order and are unverified until a QS6 ROM directory is read.\n")
print("static const SampleGroupDef kSampleGroups[] = {")
emit("QS6", "kbd", qs6_kbd)
emit("QS6", "drum", qs6_drum)
emit("QS78", "kbd", qs78_kbd)
emit("QS78", "drum", qs78_drum)
print("};")
import json
json.dump({"QS6kbd": qs6_kbd, "QS6drum": qs6_drum, "QS78kbd": qs78_kbd, "QS78drum": qs78_drum}, open("/tmp/sample_tables.json", "w"))
for name, t in (("QS6 kbd", qs6_kbd), ("QS6 drum", qs6_drum), ("QS78 kbd", qs78_kbd), ("QS78 drum", qs78_drum)):
    print(f"// {name}: " + ", ".join(f"{g}:{len(n)}" for g, n in sorted(t.items())), file=sys.stderr)

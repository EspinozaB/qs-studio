#!/usr/bin/env python3
"""Generate core/qs_params_table.inc from the Alesis "QS6,7,8,R MIDI SYSEX SPECIFICATION" (Feb 1997).

Usage: python3 tools/gen_params.py path/to/Alesis-QS678R.txt > core/qs_params_table.inc
The spec text itself is not part of this repo.
"""
import re, sys

lines = open(sys.argv[1], encoding="latin-1").read().splitlines()

def section(start, end):
    i = next(n for n, l in enumerate(lines) if l.strip().startswith(start))
    j = next(n for n, l in enumerate(lines) if n > i and l.strip().startswith(end))
    return lines[i:j]

ROW = re.compile(r"^(\d+)\.\s+(.+?)\t(\d+)\*?\t(\d+)\t(\d+)\t(-?\d+)\t\s*(\d+)\*?\t\s*(\d+)\s*\t(\d+):(\d+)(?:-(\d+):(\d+))?")

def rows(sec):
    out = []
    for l in sec:
        m = ROW.match(l.strip("\n"))
        if not m:
            continue
        num, name, func, page, pot, off, lim, bits, hb, hbit, lb, lbit = m.groups()
        lo = (int(lb) * 8 + int(lbit)) if lb is not None else (int(hb) * 8 + int(hbit))
        out.append(dict(num=int(num), name=name.strip(), func=int(func), page=int(page), pot=int(pot),
                        off=int(off), lim=int(lim), bits=int(bits), lo=lo))
    return out

kbd = rows(section("Keyboard Sound:", "Drum Sound:"))
drum = rows(section("Drum Sound:", "EFFECT DATA FORMAT"))
drum1 = [r for r in drum if r["name"].startswith("Drum 1 ")]
other_drum = [r for r in drum if not r["name"].startswith("Drum 1 ")]

def emit(name, rs, strip=None):
    print(f"static const ParamDef {name}[] = {{")
    for r in rs:
        n = r["name"]
        if strip and n.startswith(strip):
            n = n[len(strip):]
        n = n[0].upper() + n[1:]
        print(f'    {{"{n}", {r["lo"]}, {r["bits"]}, {r["off"]}, {r["lim"]}, {r["func"]}, {r["page"]}, {r["pot"]}}},')
    print("};\n")

print("// Generated by tools/gen_params.py from the Alesis QS6,7,8,R SysEx spec (Feb 1997). Do not edit by hand.")
print("// Fields: name, low bit (within the 85-byte sound), bits, offset, limit (raw), func, page, pot.\n")
emit("kKeyboardSoundParams", kbd, "Sound ")
emit("kDrumParams", drum1, "Drum 1 ")
emit("kDrumSoundParams", other_drum)
print(f"// {len(kbd)} keyboard-sound params, {len(drum1)} per-drum params, {len(other_drum)} drum-sound params")

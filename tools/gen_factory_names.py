#!/usr/bin/env python3
"""Builds core/qs_factory_names.inc: the NAMES (only) of the factory Preset 1-3 and GenMIDI programs and mixes.

Usage: gen_factory_names.py Q678PST1.SYX Q678PST2.SYX Q678PST3.SYX Q678PST4.SYX > core/qs_factory_names.inc

Only the 10-character names are kept, so a new user sees the preset names before reading anything from their synth.
No program, mix or effect data is copied into QS Studio.
"""
import sys


def unpack7(data, out_len):
    acc = nbits = 0
    res = []
    for x in data:
        acc |= (x & 0x7F) << nbits
        nbits += 7
        while nbits >= 8 and len(res) < out_len:
            res.append(acc & 0xFF)
            acc >>= 8
            nbits -= 8
    return res


def name_at(buf, start_bit):
    s = ""
    for k in range(10):
        v = 0
        for i in range(7):
            b = start_bit + 7 * k + i
            v |= ((buf[b // 8] >> (b % 8)) & 1) << i
        s += chr(v + 32) if v < 95 else "?"
    return s


def messages(path):
    d = open(path, "rb").read()
    i = 0
    while True:
        a = d.find(b"\xf0", i)
        if a < 0:
            return
        b = d.find(b"\xf7", a)
        yield d[a:b + 1]
        i = b + 1


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


progs, mixes = [], []
for path in sys.argv[1:5]:
    p = [""] * 128
    m = [""] * 100
    for msg in messages(path):
        op, num = msg[5], msg[6]
        if op == 0x00 and num < 128:
            p[num] = name_at(unpack7(msg[7:-1], 350), 8)
        elif op == 0x0E and num < 100:
            m[num] = name_at(unpack7(msg[7:-1], 138), 5)
    progs.append(p)
    mixes.append(m)

print("// Generated by tools/gen_factory_names.py from the factory bank files. Names only.")
print("// Index 0-3 = Preset 1, Preset 2, Preset 3, GenMIDI.")
print("static const char* const kFactoryProgramNames[4][128] = {")
for p in progs:
    print("    {" + ", ".join(c_str(x) for x in p) + "},")
print("};")
print("static const char* const kFactoryMixNames[4][100] = {")
for m in mixes:
    print("    {" + ", ".join(c_str(x) for x in m) + "},")
print("};")
